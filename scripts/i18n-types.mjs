import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { parseCatalogSource } from "./lib/catalog-source.mjs";

for (const { folder, file, name } of [
  { folder: "", file: "message-contract.d.ts", name: "MessageContract" },
  { folder: "pricing/", file: "pricing-message-contract.d.ts", name: "PricingMessageContract" },
]) {
  const catalogs = Object.fromEntries(["ru", "en", "uz"].map((locale) => [locale,
    parseCatalogSource(readFileSync(new URL(`../src/i18n/messages/${folder}${locale}.json`, import.meta.url), "utf8"), `${folder}${locale}.json`),
  ]));
  const target = new URL(`../src/i18n/${file}`, import.meta.url);
  const declaration = `// Generated by npm run i18n:types. Do not edit by hand.\nexport type ${name} = ` + JSON.stringify(catalogs.ru, null, 2) + ";\n";
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== declaration) {
      throw new Error(`${name} is stale. Run npm run i18n:types.`);
    }
  } else {
    writeFileSync(target, declaration);
  }
  if (folder === "") {
    for (const [locale, messages] of Object.entries(catalogs)) {
      // Client-only fallbacks and portals must not download the full site catalog.
      for (const [domain, selected] of Object.entries({
        confirm: { common: { delete: messages.common.delete, save: messages.common.save, cancel: messages.common.cancel, close: messages.common.close }, journalControls: { confirm: messages.journalControls.confirm } },
        errors: { errorSurface: messages.errorSurface },
      })) {
        const directory = new URL(`../src/i18n/messages/${domain}/`, import.meta.url);
        const file = new URL(`${locale}.json`, directory);
        const content = JSON.stringify(selected, null, 2) + "\n";
        if (process.argv.includes("--check")) {
          if (readFileSync(file, "utf8") !== content) throw new Error(`${domain}/${locale} is stale. Run npm run i18n:types.`);
        } else {
          mkdirSync(directory, { recursive: true });
          writeFileSync(file, content);
        }
      }
    }
  }
}
