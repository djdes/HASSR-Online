import type { JournalInfo } from "@/content/journal-info";

/**
 * Вопросы-ответы для страницы журнала `/journals-info/<code>`.
 *
 * Зачем это вообще понадобилось. Съём позиций 2026-09-10 показал, что по
 * запросам вида «журнал учёта стекла» Яндекс показывает сводную
 * `/blanki`, а не страницу самого журнала: у сводной 750 слов, пять
 * подзаголовков и FAQ-разметка, у каталожной — 290 слов, ноль
 * подзаголовков и никакой разметки. Страница журнала проигрывала
 * собственной витрине.
 *
 * Почему ответы собираются из данных журнала, а не пишутся одним
 * шаблоном на все страницы журналов: одинаковый блок на трёх десятках адресов —
 * это ровно тот дубликат, из-за которого поисковик и выбирает одну
 * «главную» страницу вместо профильных. Каждый ответ здесь опирается на
 * поля конкретного журнала (`whatToFill`, `normative`, `category`),
 * поэтому тексты расходятся между страницами.
 */

export type JournalFaqItem = { q: string; a: string };

/** Как часто ведётся журнал — из категории каталога. */
function cadence(info: JournalInfo): string {
  if (info.category === "sanpin_daily") {
    return "Каждую смену: запись делается в день события, задним числом её вносить нельзя — по ровным датам и одинаковым значениям инспектор как раз и вычисляет формальный учёт.";
  }
  if (info.category === "sanpin_periodic") {
    return "По графику, а не ежедневно: периодичность закрепляется в программе производственного контроля и должна совпадать с фактическими записями.";
  }
  return "По плану ХАССП: периодичность задаётся при описании контрольной точки и обосновывается в самом плане.";
}

/**
 * Склоняет название в винительный падеж для вопросов «как вести …».
 * Полноценной морфологии не заводим: названия каталога однотипны
 * («Журнал X», «График X», «Чек-лист X»), и правило для них предсказуемо.
 */
function accusative(name: string): string {
  const map: Array<[RegExp, string]> = [
    [/^Журнал\b/, "журнал"],
    [/^График\b/, "график"],
    [/^Чек-лист\b/, "чек-лист"],
    [/^Акт\b/, "акт"],
    [/^Перечень\b/, "перечень"],
    [/^Протокол\b/, "протокол"],
    [/^План\b/, "план"],
    [/^Отчёт\b/, "отчёт"],
  ];
  for (const [re, word] of map) {
    if (re.test(name)) return name.replace(re, word);
  }
  // Незнакомая форма — оставляем как есть, кривого падежа лучше избежать.
  return name.charAt(0).toLowerCase() + name.slice(1);
}

export function buildJournalFaq(
  info: JournalInfo,
  name: string
): JournalFaqItem[] {
  const subject = accusative(name);
  const items: JournalFaqItem[] = [];

  if (info.whatToFill.length > 0) {
    const fields = info.whatToFill
      .map((field) => field.replace(/\s*\(.*?\)\s*/g, " ").trim())
      .filter(Boolean);
    items.push({
      q: `Что писать в ${subject}?`,
      a: `Обязательные графы: ${fields.join("; ")}. Пустая графа для инспектора равнозначна незаполненному журналу, поэтому прочерк лучше ставить осознанно и с пояснением.`,
    });
  }

  items.push({
    q: `Как часто заполнять ${subject}?`,
    a: cadence(info),
  });

  if (info.normative.length > 0) {
    const norms = info.normative
      .map((n) => (n.pointer ? `${n.title}, ${n.pointer}` : n.title))
      .join("; ");
    items.push({
      q: `На основании какого документа ведётся ${subject}?`,
      a: `${norms}. Норматив стоит указывать на титульном листе — так проверяющий сразу видит, что журнал заведён не «на всякий случай».`,
    });
  }

  items.push({
    q: `Можно ли вести ${subject} в электронном виде?`,
    a: "Да. СанПиН 2.3/2.4.4282-26 не требует бумаги: важно, чтобы было видно, кто внёс запись и когда, и чтобы её нельзя было незаметно исправить задним числом. Для проверки электронный журнал выводится на печать за нужный период.",
  });

  items.push({
    q: `Сколько хранить ${subject}?`,
    a: "Инспектор обычно запрашивает записи за последние 12 месяцев, поэтому год — практический минимум. Журналы, связанные с расследованием отравления или претензией, хранят до закрытия разбирательства.",
  });

  return items;
}

/** FAQPage-разметка для расширенного сниппета. */
export function journalFaqJsonLd(faq: JournalFaqItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faq.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: { "@type": "Answer", text: item.a },
    })),
  };
}
