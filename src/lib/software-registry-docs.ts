function normalizeSeller(sellerInput?: BrandSeller): BrandSeller {
  const s = sellerInput ?? DEFAULT_BFS_SELLER;
  return {
    ...DEFAULT_BFS_SELLER,
    ...s,
    nameShort: s.nameShort || DEFAULT_BFS_SELLER.nameShort,
    nameFull: s.nameFull || DEFAULT_BFS_SELLER.nameFull,
    inn: s.inn || DEFAULT_BFS_SELLER.inn,
    kpp: s.kpp || DEFAULT_BFS_SELLER.kpp,
    ogrn: s.ogrn || DEFAULT_BFS_SELLER.ogrn,
    address: s.address || DEFAULT_BFS_SELLER.address,
    phone: s.phone || DEFAULT_BFS_SELLER.phone,
    email: s.email || DEFAULT_BFS_SELLER.email,
    site: s.site || "wesetup.ru",
  };
}

function drawDocumentTitleBlock(
  pdf: BrandPdf,
  flow: BrandFlow,
  meta: {
    code: string;
    title: string;
    subtitle: string;
    seller: BrandSeller;
  },
): void {
  const { doc } = pdf;
  const x = BRAND_PAGE.side;
  const width = BRAND_PAGE.contentW;

  eyebrow(
    pdf,
    `Эксплуатационная и техническая документация ПО «WeSetup» · Шифр ${meta.code} · Версия ${SOFTWARE_REGISTRY_VERSION}`,
    x,
    flow.y + 3.2,
  );
  flow.gap(5.2);

  setText(pdf, { size: 15.5, weight: "semibold", color: C.ink });
  const titleLines = doc.splitTextToSize(meta.title, width) as string[];
  doc.text(titleLines, x, flow.y + 5.2);
  flow.gap(titleLines.length * 6.4 + 1.5);

  setText(pdf, { size: 9, color: C.muted });
  const subLines = doc.splitTextToSize(meta.subtitle, width) as string[];
  doc.text(subLines, x, flow.y + 3.4);
  flow.gap(subLines.length * 4.2 + 2.5);

  doc.setDrawColor(...C.border2);
  doc.setLineWidth(0.2);
  doc.line(x, flow.y, x + width, flow.y);
  setText(pdf, { size: 8.5, color: C.ink2 });
  doc.text("г. Королёв, Московская область", x, flow.y + 4.8);
  doc.text(
    `Редакция от ${SOFTWARE_REGISTRY_REVISION_DATE_RU} · Правообладатель: ${meta.seller.nameShort} (ИНН ${meta.seller.inn})`,
    x + width,
    flow.y + 4.8,
    { align: "right" },
  );
  doc.line(x, flow.y + 7.2, x + width, flow.y + 7.2);
  flow.gap(11);
}

function drawHeading(flow: BrandFlow, num: string | number, title: string): void {
  flow.ensure(16);
  flow.gap(2);
  sectionTitle(flow.pdf, BRAND_PAGE.side, flow.y + 4, { num: String(num), title });
  flow.gap(6.6);
}

function drawTable(
  flow: BrandFlow,
  head: CellInput[][],
  body: CellInput[][],
  columnStyles?: Record<number, { cellWidth?: number }>,
): void {
  flow.ensure(22);
  const finalY = dataTable(flow.pdf, {
    startY: flow.y,
    head,
    body,
    columnStyles,
    zebra: true,
    fontSize: 8.2,
  });
  flow.y = finalY + 4;
}

function drawApprovalFooter(
  pdf: BrandPdf,
  flow: BrandFlow,
  seller: BrandSeller,
  images: LegalSignImages,
  docCode: string,
): void {
  const { doc } = pdf;
  const x = BRAND_PAGE.side;
  const width = BRAND_PAGE.contentW;

  flow.ensure(46);
  flow.gap(4);

  const signTop = flow.y;
  const qrSize = 27;
  const qrX = x + width - qrSize;
  drawFramedQr(pdf, SOFTWARE_REGISTRY_URL, { x: qrX, y: signTop, size: qrSize });
  setText(pdf, { size: 6.8, color: C.muted });
  doc.text("wesetup.ru/reestr-po", qrX + qrSize / 2, signTop + qrSize + 3.4, {
    align: "center",
  });

  signatureLine(pdf, {
    x,
    y: signTop + 1,
    width: width - qrSize - 12,
    post: `УТВЕРЖДАЮ · ${GOOGLE_PLAY_AUTH_SIGNER_POST_RU} (${seller.nameFull})`,
    name: `${GOOGLE_PLAY_AUTH_SIGNER_SHORT_RU} · ${SOFTWARE_REGISTRY_REVISION_DATE_RU}`,
    facsimile: images.facsimile,
    stamp: images.stamp,
  });

  decoratePages(pdf, seller, {
    pageLabel: (page, total) =>
      `${docCode} · ПО «WeSetup» (${seller.nameShort}, ИНН ${seller.inn}) · Стр. ${page} из ${total}`,
  });
}

