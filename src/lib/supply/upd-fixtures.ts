/**
 * Образцы УПД для тестов (не используются в приложении): 5.01 от юрлица,
 * как его отдаёт Диадок, и 5.03 от ИП в UTF-8. `toCp1251` — кодировка, в
 * которой УПД обычно приходят из ЭДО.
 */

export function toCp1251(text: string): Uint8Array {
  const out: number[] = [];
  for (const char of text) {
    const code = char.codePointAt(0)!;
    if (code < 0x80) out.push(code);
    else if (code >= 0x410 && code <= 0x44f) out.push(code - 0x410 + 0xc0);
    else if (code === 0x401) out.push(0xa8);
    else if (code === 0x451) out.push(0xb8);
    else if (code === 0x2116) out.push(0xb9);
    else if (code === 0xab) out.push(0xab);
    else if (code === 0xbb) out.push(0xbb);
    else throw new Error(`Нет в windows-1251: ${char}`);
  }
  return Uint8Array.from(out);
}

