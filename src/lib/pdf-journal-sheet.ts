import type { jsPDF } from "jspdf";

/**
 * Поля листа печатного журнала — ОДНО значение для всех четырёх сторон.
 *
 * На каждой странице бланка (первой и продолжениях, книжной и альбомной):
 *   • сверху — шапка ХАССП (или крупный заголовок над ней) начинается в
 *     `JOURNAL_SHEET_MARGIN_MM` от верхнего края листа; на продолжениях без
 *     шапки так же начинается таблица;
 *   • слева и справа — шапка и таблицы от края до края между полями;
 *   • снизу — низ маленького QR в углу (и «СТР. X ИЗ N», подвал партнёра)
 *     стоит на той же линии в `JOURNAL_SHEET_MARGIN_MM` от нижнего края.
 *
 * Раньше шапка стояла на 28 мм сверху (место под крупный заголовок, который
 * у гигиены, здоровья, климата и других в печать не идёт), таблицы на
 * продолжениях — на 14 мм (поле autoTable по умолчанию), а QR — на 5 мм от
 * низа: верхнее поле выходило вдвое больше боковых и нижнего.
 */
export const JOURNAL_SHEET_MARGIN_MM = 10;

/** Высота прописной буквы DejaVu Sans в долях кегля. */
export const JOURNAL_CAP_HEIGHT_EM = 0.73;
/** Выносной элемент строчных («р», «у», «д») DejaVu Sans ниже базовой линии, доли кегля. */
export const JOURNAL_DESCENT_EM = 0.24;

/**
 * Зазор от крупного заголовка бланка (низ выносных строчных) до шапки ХАССП
 * под ним, мм. Раньше заголовок стоял базовой линией на 15 мм, а шапка —
 * на 28 мм: между ними было ~11 мм пустоты.
 */
export const JOURNAL_TITLE_HEADER_GAP_MM = 4;

/**
 * Полоса под текстом подвала (кегль 10 pt «СТР. X ИЗ N» стоит базовой линией
 * на нижнем поле): столько таблица оставляет над нижним полем, когда QR в
 * угол не резервируется, — чтобы подпись страницы не легла на таблицу.
 */
export const JOURNAL_FOOTER_TEXT_BAND_MM = 4;
/** То же для подвала партнёра в две строки (7 pt, шаг 3,4 мм). */
export const JOURNAL_FOOTER_TEXT_BAND_BRANDED_MM = 6.5;

/** Кегль текущего шрифта документа, мм. */
function fontSizeMm(doc: jsPDF): number {
  return (doc.getFontSize() * 25.4) / 72;
}

/** Высота прописных текущего кегля, мм. */
export function journalCapHeightMm(doc: jsPDF): number {
  return fontSizeMm(doc) * JOURNAL_CAP_HEIGHT_EM;
}

/** Выносной элемент строчных текущего кегля, мм. */
export function journalDescentMm(doc: jsPDF): number {
  return fontSizeMm(doc) * JOURNAL_DESCENT_EM;
}

/**
 * Базовая линия первой строки текста текущего кегля, у которой верх
 * прописных ровно на верхнем поле листа.
 */
export function journalSheetTopBaseline(doc: jsPDF): number {
  return JOURNAL_SHEET_MARGIN_MM + journalCapHeightMm(doc);
}
