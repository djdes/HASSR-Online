function safetyRules(kind: VisionInstructionKind): readonly string[] {
  return kind === "label" || kind === "reading" || kind === "photo_check" ? SINGLE_SAFETY_RULES[kind] : VISION_SAFETY_RULES;
}

/**
 * Инструкция исполнителю для вида. Всё, что нужно модели, — здесь; фото —
 * отдельными блоками. Для проверки фото-доказательства — что на нём должно
 * быть; для показания дисплея — какой показатель нужен (кнопка «Фото» у
 * поля температуры или влажности).
 */
export function buildVisionInstruction(
  kind: VisionInstructionKind,
  options: { expected?: PhotoCheckExpected; metric?: ReadingMetric; zoom?: boolean } = {}
): string {
  const task = TASKS[kind];
  const intro = task.intro ?? `Задача: распознать текст на фото и вернуть ${task.what}. Фото — это снимки документа с телефона.`;
  const context = kind === "photo_check" ? [`Что должно быть на фото: ${PHOTO_CHECK_HINTS[options.expected ?? "any"]}.`] : [];
  const metric = kind === "reading" ? options.metric : undefined;
  const mapped = metric
    ? task.details.map((line) => (line === READING_SEVERAL_NUMBERS ? READING_METRIC_HINTS[metric] : line))
    : task.details;
  // Второе фото — увеличенный фрагмент у верха столбика (`reading-zoom.ts`).
  const details = kind === "reading" && options.zoom ? [...mapped, READING_ZOOM_NOTE] : mapped;
  return [
    intro,
    ...context,
    "",
    ...details,
    "",
    "Правила:",
    ...safetyRules(kind).map((rule, index) => `${index + 1}. ${rule}`),
    "",
    `Формат ответа — строго один JSON: ${task.format}`,
    task.empty,
  ].join("\n");
}

/** Ссылка на картинку для строки `image_url:` — абсолютная http(s), без пробелов и переводов строк. */
function assertImageUrl(url: string): void {
  if (!/^https?:\/\/[^\s]+$/.test(url)) throw new Error(`vision: bad image url`);
}

/** Полный текст задания: заголовок со ссылками, `---`, инструкция. */
export function buildVisionJobText(args: { imageUrls: string[]; instruction: string }): string {
  const { imageUrls, instruction } = args;
  if (imageUrls.length < 1 || imageUrls.length > VISION_MAX_PHOTOS) {
    throw new Error(`vision: expected 1-${VISION_MAX_PHOTOS} images, got ${imageUrls.length}`);
  }
  imageUrls.forEach(assertImageUrl);
  return [`type: ${VISION_JOB_TYPE}`, ...imageUrls.map((url) => `image_url: ${url}`), "---", instruction.trim()].join("\n");
}
