/**
 * Отпечаток содержимого заметок.
 *
 * Окно «Что нового» было выключено в августе (`c333ca3e`) именно из-за
 * привязки к SHA сборки: SHA менялся, текст оставался прежним, и люди
 * при каждом входе видели одно и то же как новость.
 *
 * Теперь показ зависит от САМОГО ТЕКСТА. Не изменили заметки — окно не
 * появится, сколько бы раз ни поднимали SHA. Изменили — появится один
 * раз, даже если SHA забыли тронуть. Ошибиться так, как раньше, больше
 * нельзя.
 *
 * Алгоритм намеренно простейший (djb2): это не защита, а различение
 * двух текстов, и он должен одинаково считаться на сервере и в браузере
 * без зависимостей.
 */
export function whatsNewVersion(notes: WhatsNewNote[] = WHATS_NEW_NOTES): string {
  const text = JSON.stringify(notes);
  let hash = 5381;
  for (let i = 0; i < text.length; i++) {
    hash = ((hash << 5) + hash + text.charCodeAt(i)) | 0;
  }
  return (hash >>> 0).toString(36);
}
