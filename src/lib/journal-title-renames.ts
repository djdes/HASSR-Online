/**
 * Переименованные журналы: старые названия → новые.
 *
 * 2026-09-28 (владелец): «Это не бланк, а журнал учёта температурного режима
 * холодильного и морозильного оборудования в соответствии с Приложением № 2
 * СанПиН 2.3/2.4.4282-26… не должно быть слова „бланк“». Журнал складов
 * назывался «Бланк контроля…», холодильный — «Журнал контроля…».
 *
 * Имя шаблона каталог и сид обновляют сами, а заголовок уже созданного
 * документа лежит в БД строкой с момента создания (точное название или
 * автоназвание «название — период»). По этим спискам его переименовывает
 * `prisma/seed-rename-climate-title.ts` (на каждом деплое, идемпотентно), а
 * печать (`document-pdf.ts`) печатает старое название новым, если документ
 * ещё не переименован. Названия, набранные руками, под списки не попадут.
 *
 * Модуль без импортов — его берёт и сид (tsx вне Next).
 */
export type JournalTitleRename = {
  /** `JournalTemplate.code`. */
  code: string;
  /** Нынешнее название (= каталог `journal-catalog.ts`). */
  title: string;
  /** Прежние названия — точным совпадением (регистр важен). */
  legacyTitles: readonly string[];
};

export const JOURNAL_TITLE_RENAMES: readonly JournalTitleRename[] = [
  {
    code: "climate_control",
    title: "Журнал учёта температуры и влажности на складах",
    legacyTitles: [
      "Бланк контроля температуры и влажности на складах",
      "Бланк контроля температуры и влажности",
      "Журнал контроля температуры и влажности",
      "Контроль температуры и влажности",
    ],
  },
  {
    code: "cold_equipment_control",
    title: "Журнал учёта температурного режима холодильного и морозильного оборудования",
    legacyTitles: ["Журнал контроля температурного режима холодильного и морозильного оборудования"],
  },
];

/** Разделитель автоназвания «название — период» (`journal-document-title.ts`). */
const NAME_SEPARATOR = " — ";

/**
 * Заголовок документа с нынешним названием журнала: старое название целиком
 * или в начале автоназвания «старое название — период» (период сохраняется).
 * Всё остальное — как есть.
 */
export function renamedJournalDocumentTitle(code: string, title: string): string {
  const rename = JOURNAL_TITLE_RENAMES.find((item) => item.code === code);
  if (!rename) return title;
  for (const legacy of rename.legacyTitles) {
    if (title === legacy) return rename.title;
    if (title.startsWith(`${legacy}${NAME_SEPARATOR}`)) return `${rename.title}${title.slice(legacy.length)}`;
  }
  return title;
}
