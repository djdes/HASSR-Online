/**
 * Каталог платных услуг: экспертная работа вокруг журналов, которую
 * нельзя автоматизировать — аудит, разработка документации, выезд,
 * консультация.
 *
 * Цены живут в БД (`PlatformService`) и правятся ROOT'ом в
 * /root/services — точно так же, как тарифы подписки в
 * `src/lib/tariffs.ts`. Смена прайса не требует деплоя, а деплой не
 * затирает то, что владелец поправил руками: сидирование
 * идемпотентное и срабатывает только на пустой таблице.
 *
 * Client-safe: файл импортируют и серверные модули, и карточки в
 * кабинете, поэтому здесь нет ни prisma, ни node-api. Чтение из БД
 * живёт в соседнем `./catalog`. Тем же приёмом разделён баланс
 * (`src/lib/balance/constants.ts`) — без этого Next затаскивает `pg`
 * в браузерный бандл и страница падает на «Can't resolve 'tls'».
 */

