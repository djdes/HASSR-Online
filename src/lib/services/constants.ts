/**
 * Услуги, которых не было в первом засеве. Непустую таблицу (её уже
 * могли поправить руками) они не получают сами: `readServices` досеивает
 * именно эти ключи. Удалённую админом услугу из списка так вернём — поэтому
 * выключать её надо через `active`, а не удалением.
 */
export const SERVICES_ADDED_LATER = ["pest-control-service", "norms-subscription"] as const;

/** Стартовые услуги из `SERVICES_ADDED_LATER`, которых нет среди уже записанных ключей. */
export function missingLaterServices(existingKeys: readonly string[]): PlatformServiceItem[] {
  const present = new Set(existingKeys);
  return DEFAULT_SERVICES.filter(
    (item) => (SERVICES_ADDED_LATER as readonly string[]).includes(item.key) && !present.has(item.key)
  );
}

/**
 * Подпись цены: «5 000 ₽ за услугу», «от 15 000 ₽ за аудит»,
 * «Цена по запросу». Чистая функция — зовётся и на сервере, и в
 * клиентских карточках.
 */
export function formatServicePrice(item: {
  priceRub: number | null;
  priceFrom: boolean;
  unit: string | null;
}): string {
  if (item.priceRub === null) return "Цена по запросу";
  const amount = item.priceRub.toLocaleString("ru-RU");
  const prefix = item.priceFrom ? "от " : "";
  const suffix = item.unit ? ` ${item.unit}` : "";
  return `${prefix}${amount} ₽${suffix}`;
}

/**
 * Можно ли оплатить услугу баллами сразу.
 *
 * Только фиксированная цена: «от 15 000 ₽» — это оценка до разговора,
 * и списывать по ней нельзя, иначе клиент заплатит за одно, а получит
 * счёт на другое.
 */
export function isInstantPayable(item: {
  priceRub: number | null;
  priceFrom: boolean;
}): boolean {
  return item.priceRub !== null && item.priceRub > 0 && !item.priceFrom;
}

/** Группировка для вывода каталога. */
export function groupServices(items: PlatformServiceItem[]): Array<{
  category: ServiceCategory;
  label: string;
  items: PlatformServiceItem[];
}> {
  return SERVICE_CATEGORY_ORDER.map((category) => ({
    category,
    label: SERVICE_CATEGORY_LABEL[category],
    items: items.filter((item) => item.category === category),
  })).filter((group) => group.items.length > 0);
}
