/**
 * Пропорции фирменного QR WeSetup — общие для сервера (`brand-qr.ts`,
 * рисует код) и клиента (задаёт размеры картинок в диалогах). Здесь
 * только числа: файл импортируется из клиентских компонентов, поэтому
 * без `qrcode`, `node:fs` и прочего серверного.
 *
 * Плитка (2026-09-27, ч/б): один чёрный блок шириной W — тонкая рамка слева,
 * сверху и справа, внутри белое окно с кодом и его тихой зоной, снизу рамка
 * утолщается в полосу со словом «Отсканировать». Доли — от W, поэтому
 * отношение высоты к ширине одно для любого адреса.
 */

/** Рамка слева, сверху и справа, доля W. */
export const BRAND_QR_FRAME = 0.012;
/** Полоса под окном кода (утолщение рамки снизу со словом), доля W. */
export const BRAND_QR_STRIP = 0.16;

/**
 * Высота ÷ ширина плитки с полосой: рамка сверху + окно (квадрат W − 2 рамки)
 * + полоса. Без полосы — квадрат, 1.
 */
export const BRAND_QR_CAPTION_ASPECT = 1 - BRAND_QR_FRAME + BRAND_QR_STRIP;

/** Высота картинки QR с полосой по её ширине, px (округление вверх — без обрезки). */
export function brandQrHeightFor(width: number): number {
  return Math.ceil(width * BRAND_QR_CAPTION_ASPECT);
}
