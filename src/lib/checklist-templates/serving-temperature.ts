/**
 * Типовой чек-лист «Контроль температуры готовых блюд на раздаче»
 * (задача руководителя 05.11.2026, п. 1).
 *
 * Блюда подгружаются сами: категория «Блюдо на раздаче» — образец карточки
 * (`rowsSource: "serving_dishes"`), при старте проверки сервер кладёт в неё
 * сегодняшние блюда бракеража и готовую продукцию справочника
 * (`src/lib/serving-dishes.ts`). На каждое блюдо — как подаётся и два замера:
 * в начале раздачи и через час после начала.
 *
 * Нормы — те же, что в типовом чек-листе СанПиН (`sanpin.ts`): горячие
 * вторые блюда и гарниры — не ниже +65 °C, первые блюда и горячие напитки —
 * не ниже +75 °C, холодные блюда и напитки — не выше +14 °C, «если иное не
 * установлено технологической документацией». Пороги — условия нарушения
 * вопросов: организация меняет их в конструкторе своей копии шаблона.
 */
import type { ChecklistCondition } from "@/lib/custom-checklist-rules";
import { buildDefinition, category, datetime, info, section, text, type QuestionDraft, type TypicalChecklistTemplate } from "./builder";

const PREFIX = "serving-temp";
/** id вопроса «Как подаётся блюдо»: `buildDefinition` нумерует по порядку (info, время, выбор). */
export const SERVING_GROUP_QUESTION_ID = `${PREFIX}-q3`;

type Group = { value: "hot" | "soup" | "cold"; name: string; violation: ChecklistCondition; norm: string; min: number; max: number };
const GROUPS: Group[] = [
  { value: "hot", name: "горячее", violation: { operator: "lt", value: 65 }, norm: "не ниже +65 °C", min: 0, max: 100 },
  { value: "soup", name: "первое или горячий напиток", violation: { operator: "lt", value: 75 }, norm: "не ниже +75 °C", min: 0, max: 100 },
  { value: "cold", name: "холодное", violation: { operator: "gt", value: 14 }, norm: "не выше +14 °C", min: -10, max: 50 },
];

const groupChoice: QuestionDraft = {
  title: "Как подаётся блюдо",
  description:
    "От выбора зависит норма. У блюд из справочника он уже стоит. Блюда нет на линии — «Сегодня нет на раздаче».",
  type: "choice",
  active: true,
  required: true,
  weight: 0,
  min: 0,
  max: 10,
  options: [
    { value: "hot", label: "Горячее второе блюдо или гарнир — не ниже +65 °C", score: 1 },
    { value: "soup", label: "Первое блюдо или горячий напиток — не ниже +75 °C", score: 1 },
    { value: "cold", label: "Холодное блюдо или напиток — не выше +14 °C", score: 1 },
    { value: "absent", label: "Сегодня нет на раздаче", score: 1, excluded: true },
  ],
};

function measurement(group: Group, moment: "start" | "hour"): QuestionDraft {
  const when = moment === "start" ? "в начале раздачи" : "через час после начала раздачи";
  return {
    title: `Температура ${when} (${group.name})`,
    description:
      moment === "start"
        ? `Щуп — в центр блюда, не касаясь посуды. Норма — ${group.norm}.`
        : `Второй замер тем же способом через час после начала раздачи. Норма — ${group.norm}.`,
    type: "number",
    active: true,
    required: true,
    weight: 1,
    min: group.min,
    max: group.max,
    step: 0.1,
    unit: "°C",
    options: [],
    showIf: { questionId: SERVING_GROUP_QUESTION_ID, operator: "eq", value: group.value },
    violation: group.violation,
    logic: [{ condition: group.violation, actions: { comment: true } }],
  };
}

