const BY_CODE = new Map(ORDER_TEMPLATES.map((item) => [item.code, item]));

export function findOrderTemplate(code: string): OrderTemplate | null {
  return BY_CODE.get(code) ?? null;
}

export function isOrderTemplateCode(code: string): boolean {
  return BY_CODE.has(code);
}

/** Шаблоны, сгруппированные по категориям в порядке вывода. */
export function groupedOrderTemplates(): Array<{
  category: OrderCategory;
  label: string;
  items: OrderTemplate[];
}> {
  return ORDER_CATEGORY_ORDER.map((category) => ({
    category,
    label: ORDER_CATEGORY_LABEL[category],
    items: ORDER_TEMPLATES.filter((item) => item.category === category),
  })).filter((group) => group.items.length > 0);
}
