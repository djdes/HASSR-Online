/**
 * Каталог шаблонов приказов по предприятию.
 *
 * Зачем это в продукте. Журналы отвечают на вопрос «что делали», а
 * приказы — «кто за это отвечает». Инспектор спрашивает и то, и другое:
 * журнал уборки без приказа о назначении ответственного за санитарное
 * состояние — бумага, которую никто не обязан вести. До сих пор клиент
 * искал такие шаблоны на стороне и вбивал реквизиты руками, хотя они у
 * нас уже есть в `Organization.legalProfileJson`.
 *
 * Файл — чистые данные, без prisma и node-api: его импортируют и
 * серверные роуты, и публичная страница /prikazy, и клиентская форма
 * предпросмотра.
 *
 * Плейсхолдеры в `body` и `header`:
 *   {{orgName}}      — полное название с ОПФ
 *   {{orgShortName}} — короткое название
 *   {{orgInn}}       — ИНН или прочерк
 *   {{orgAddress}}   — юридический адрес или прочерк
 *   {{directorName}} — ФИО руководителя
 *   {{directorPost}} — должность руководителя («Генеральный директор»)
 *   {{number}}       — номер приказа
 *   {{issuedAt}}     — дата издания, «10 сентября 2026 г.»
 *   {{city}}         — город издания
 *   плюс любые `key` из `fields`.
 *
 * Подстановка — `renderOrder` в `./render`.
 */

export type OrderFieldKind = "text" | "person" | "post" | "date" | "textarea";

export type OrderField = {
  key: string;
  label: string;
  kind: OrderFieldKind;
  /** Подсказка под полем: что именно писать. */
  hint?: string;
  required: boolean;
  /** Значение по умолчанию — подставляется в пустую форму. */
  defaultValue?: string;
};

export type OrderCategory = "haccp" | "sanitary" | "staff" | "equipment";

export type OrderTemplate = {
  code: string;
  /** Заголовок приказа без слова «Приказ»: «О назначении…». */
  title: string;
  category: OrderCategory;
  /** Одна строка для карточки: зачем этот приказ нужен. */
  purpose: string;
  /**
   * Нормативные основания — печатаются в преамбуле.
   *
   * Пункты СанПиН 2.3/2.4.4282-26 сверены с текстом правил 2026-09-26
   * (consultant.ru, cons_doc_LAW_535846). Нумерация в нём сквозная,
   * пункты 1–65: номера вида «2.18» — от отменённого предшественника.
   */
  basis: string[];
  fields: OrderField[];
  /** Абзацы постановляющей части. Пустая строка = отбивка. */
  body: string[];
};

