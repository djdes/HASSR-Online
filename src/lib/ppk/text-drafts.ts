import type { PpkTextBlock } from "./records";

export const DRAFT_BLOCKS = [
  "text-haccp-principles",
  "text-terms",
  "text-team-regulation",
  "text-team-leader",
  "text-ccp-method",
  "text-flow-schedule",
] as const satisfies readonly PpkTextBlock[];
export type DraftBlock = (typeof DRAFT_BLOCKS)[number];

export function isDraftBlock(value: unknown): value is DraftBlock {
  return typeof value === "string" && (DRAFT_BLOCKS as readonly string[]).includes(value);
}

/** Тип задания очереди: генератор документов, который воркер уже исполняет. */
