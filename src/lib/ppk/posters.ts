export type PosterItem = { text: string; art?: PosterArtName };

export type PosterBlock =
  /** Карточки с картинкой сверху; по умолчанию с номерами. */
  | { type: "steps"; items: PosterItem[]; numbered?: boolean; columns?: 2 | 3 | 4 | 5 }
  /** Маркированный или нумерованный список; картинка у пункта — слева. */
  | { type: "list"; items: PosterItem[]; numbered?: boolean; art?: PosterArtName }
  /** Две колонки с ✓ и ✗ — не только цветом. */
  | {
      type: "doDont";
      doTitle: string;
      dontTitle: string;
      doArt: PosterArtName;
      dontArt: PosterArtName;
      do: string[];
      dont: string[];
    }
  /** Таблица любой ширины; `swatchColumn` — колонка с цветом разделочного инвентаря. */
  | { type: "table"; title?: string; head: string[]; rows: string[][]; swatchColumn?: number }
  | { type: "callout"; tone: "warn" | "info"; text: string; art?: PosterArtName }
  | { type: "text"; paragraphs: string[] }
  /** Образец этикетки 58×40 мм с выносками. */
  | { type: "labelSample"; callouts: { field: string; text: string }[] }
  /** QR на журнал точки (или организации); журнал выключен — QR нет, остаётся подпись. */
  | { type: "journalQr"; templateCode: string; caption: string };

