/** Плакат по ключу или null для неизвестного ключа (маршрут `posters/[key]`). */
export function findPoster(key: string): Poster | null {
  return POSTERS.find((poster) => poster.key === key) ?? null;
}

/** Плакаты выбранных ключей в порядке каталога; пусто или нет совпадений — null. */
export function selectPosters(keys: readonly string[]): Poster[] {
  const wanted = new Set(keys);
  return POSTERS.filter((poster) => wanted.has(poster.key));
}

/** Строка для сравнения названий средств: строчные, «ё» → «е», без пробелов и дефисов. */
export function normalizeDisinfectantName(value: string): string {
  return value.toLowerCase().replace(/ё/g, "е").replace(/[\s\-–—_.,]+/g, "");
}

/** Есть ли памятка среди средств журнала (названия уже нормализованы). */
export function posterInJournal(poster: Poster, normalizedJournalNames: readonly string[]): boolean {
  if (!poster.journalNames?.length) return false;
  return poster.journalNames.some((needle) => normalizedJournalNames.some((name) => name.includes(needle)));
}

/**
 * Каталог для страницы: внутри группы «Дезинфекция» памятки средств из
 * журнала учёта идут первыми (порядок сохраняется), остальное — как есть.
 */
export function orderPosters(normalizedJournalNames: readonly string[]): Poster[] {
  // Общая памятка о мерах предосторожности остаётся первой, дальше — памятки из журнала.
  const rank = (poster: Poster) => (!poster.journalNames ? 0 : posterInJournal(poster, normalizedJournalNames) ? 1 : 2);
  return POSTER_GROUPS.flatMap((group) =>
    POSTERS.filter((poster) => poster.group === group.key)
      .map((poster, index) => ({ poster, index }))
      .sort((a, b) => rank(a.poster) - rank(b.poster) || a.index - b.index)
      .map((entry) => entry.poster),
  );
}
