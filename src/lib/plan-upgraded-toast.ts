"use client";

import { toast } from "sonner";

import { FREE_SEATS_LABEL } from "@/lib/plan-catalog";

/**
 * Единый toast «вы перешли на подписку».
 *
 * Показывается там, где API вернул `planUpgraded: true` — то есть
 * добавление сотрудника перевалило за бесплатные места. Такое бывает
 * только до конца бесплатного периода (после — лимит проверяется до
 * создания, тихого перевода нет), поэтому оплата сейчас не требуется.
 * Текст один на все точки входа: смена тарифа не должна выглядеть
 * по-разному в приглашении, массовом импорте и карточке сотрудника.
 */
export function toastPlanUpgraded(): void {
  toast.info(`Сотрудников больше, чем в бесплатном тарифе (${FREE_SEATS_LABEL}) — вы перешли на подписку`, {
    description: "Сейчас оплата не требуется.",
    duration: 10000,
    action: {
      label: "Подробнее",
      onClick: () => {
        window.location.href = "/settings/subscription";
      },
    },
  });
}
