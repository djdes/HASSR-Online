export const KB_ARTICLES: KbArticle[] = KB_GROUPS.flatMap((group) => group.articles);

export function kbArticle(slug: string): KbArticle | null {
  return KB_ARTICLES.find((article) => article.slug === slug) ?? null;
}

export function kbGroupOf(slug: string): KbGroup | null {
  return KB_GROUPS.find((group) => group.articles.some((article) => article.slug === slug)) ?? null;
}

/** Соседние статьи для ссылок «Назад / Далее» внизу страницы. */
export function kbNeighbours(slug: string): { prev: KbArticle | null; next: KbArticle | null } {
  const index = KB_ARTICLES.findIndex((article) => article.slug === slug);
  return {
    prev: index > 0 ? KB_ARTICLES[index - 1] : null,
    next: index >= 0 && index < KB_ARTICLES.length - 1 ? KB_ARTICLES[index + 1] : null,
  };
}

/** Убрать разметку `**…**` и `[текст](ссылка)` — для поиска и корпуса ИИ. */
export function kbPlain(text: string): string {
  return text.replace(/\*\*(.+?)\*\*/g, "$1").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
}

/** Заголовки h2 статьи с якорями — для оглавления «На этой странице». */
export function kbHeadings(article: KbArticle): { id: string; text: string }[] {
  return article.blocks.flatMap((block, index) => (block.t === "h2" ? [{ id: `s-${index}`, text: block.text }] : []));
}
