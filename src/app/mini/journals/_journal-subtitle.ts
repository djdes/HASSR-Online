/**
 * Подпись журнала под названием.
 *
 * Описания шаблонов писались для разработчика, и на телефоне это видно:
 * «Документный журнал контроля температурного режима… по дням месяца»,
 * «…с настройками документа, таблицей проверок и печатью». Повару эти
 * слова ничего не говорят, а место на экране занимают.
 *
 * Хуже другое — у части журналов описание слово в слово повторяет
 * название, и карточка печатает одну и ту же фразу дважды.
 *
 * Чинить в базе нельзя: описания общие с сайтом и с печатными формами.
 * Поэтому правим на показе, и только явные служебные куски.
 */

/** Служебные хвосты: как устроен документ внутри, а не что вести. */
const TECHNICAL_TAIL =
  /[,\s]*(?:\s(?:с|со)\s(?:настройк\w*|таблиц\w*|справочник\w*)[^.]*|\sпо\sдням\sмесяца)\.?\s*$/iu;

/** Для сравнения: регистр, «ё» и знаки не должны мешать. */
function normalize(value: string): string {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

/**
 * Что показать под названием журнала. `null` — показывать нечего.
 */
export function journalSubtitle(
  name: string,
  description?: string | null
): string | null {
  if (!description) return null;
  let text = description.trim();
  if (!text) return null;

  // «Документный журнал …» — слово из кода, а не из жизни.
  text = text.replace(/^документн(?:ый|ая|ое)\s+/iu, "");
  if (text && text[0] === text[0].toLowerCase()) {
    text = text[0].toUpperCase() + text.slice(1);
  }

  // Хвост про устройство документа режем, пока он есть: их бывает два
  // подряд («…с таблицей записей, настройками и справочниками»).
  let previous = "";
  while (previous !== text) {
    previous = text;
    text = text.replace(TECHNICAL_TAIL, "").trim();
  }
  if (!text) return null;

  // Повтор названия — пустая строка на экране.
  if (normalize(text) === normalize(name)) return null;

  return text;
}
