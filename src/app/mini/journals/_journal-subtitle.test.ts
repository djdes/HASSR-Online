import assert from "node:assert/strict";
import test from "node:test";

import { journalSubtitle } from "./_journal-subtitle";

test("описание слово в слово повторяет название — не показываем", () => {
  assert.equal(
    journalSubtitle(
      "Чек-лист уборки и проветривания помещений",
      "Чек-лист уборки и проветривания помещений"
    ),
    null
  );
});

test("служебное «Документный журнал …» и «по дням месяца» убираются", () => {
  assert.equal(
    journalSubtitle(
      "Журнал контроля температурного режима холодильного оборудования",
      "Документный журнал контроля температурного режима холодильного оборудования по дням месяца"
    ),
    null
  );
});

test("хвост про устройство документа отрезается", () => {
  assert.equal(
    journalSubtitle(
      "Журнал контроля изделий из стекла",
      "Журнал контроля изделий из стекла и хрупкого пластика с настройками документа, таблицей проверок и печатью"
    ),
    "Журнал контроля изделий из стекла и хрупкого пластика"
  );
});

test("осмысленное описание остаётся как есть", () => {
  assert.equal(
    journalSubtitle("Журнал здоровья", "Ежедневный контроль состояния здоровья сотрудников"),
    "Ежедневный контроль состояния здоровья сотрудников"
  );
});

test("пустое описание — null", () => {
  assert.equal(journalSubtitle("Журнал уборки", null), null);
  assert.equal(journalSubtitle("Журнал уборки", "   "), null);
});
