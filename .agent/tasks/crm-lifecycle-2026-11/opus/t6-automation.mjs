import { login, sql, close } from "./lib.mjs";
const owner = await login("owner");
const alexey = await login("alexey");
const out = [];
const t = async (label, p) => { const r = await p; out.push(`${label} → ${r.status} ${JSON.stringify(r.data).slice(0, 260)}`); return r; };
const g = await t("GET settings (owner)", owner.api("GET", "/api/root/crm/automation"));
const s = g.data.settings;
const original = JSON.parse(JSON.stringify(s));
await t("GET settings (alexey, commercial director)", alexey.api("GET", "/api/root/crm/automation"));
await t("PUT empty body", owner.api("PUT", "/api/root/crm/automation", {}));
await t("PUT trialStages [0]", owner.api("PUT", "/api/root/crm/automation", { ...s, trialStages: [0] }));
await t("PUT trialStages [] (empty)", owner.api("PUT", "/api/root/crm/automation", { ...s, trialStages: [] }));
out.push("  saved trialStages: " + sql(`select value::json->>'trialStages' from "PlatformSetting" where key='crm:lifecycle'`));
await t("PUT trialStages ['4']", owner.api("PUT", "/api/root/crm/automation", { ...s, trialStages: ["4"] }));
await t("PUT trialStages 9 items", owner.api("PUT", "/api/root/crm/automation", { ...s, trialStages: [1,2,3,4,5,6,7,8,9] }));
await t("PUT discountLadder []", owner.api("PUT", "/api/root/crm/automation", { ...s, discountLadder: [] }));
out.push("  saved ladder: " + sql(`select value::json->>'discountLadder' from "PlatformSetting" where key='crm:lifecycle'`));
await t("PUT ladder duplicate minUsers", owner.api("PUT", "/api/root/crm/automation", { ...s, discountLadder: [{ minUsers: 10, percent: 10 }, { minUsers: 10, percent: 50 }] }));
out.push("  saved ladder: " + sql(`select value::json->>'discountLadder' from "PlatformSetting" where key='crm:lifecycle'`));
await t("PUT ladder non-monotonic (100+ → 5 %, 10+ → 20 %)", owner.api("PUT", "/api/root/crm/automation", { ...s, discountLadder: [{ minUsers: 100, percent: 5 }, { minUsers: 10, percent: 20 }] }));
await t("PUT ladder percent 95", owner.api("PUT", "/api/root/crm/automation", { ...s, discountLadder: [{ minUsers: 10, percent: 95 }] }));
await t("PUT defaultAssignee invalid", owner.api("PUT", "/api/root/crm/automation", { ...s, defaultAssigneeId: "nope" }));
await t("PUT defaultAssignee client user", owner.api("PUT", "/api/root/crm/automation", { ...s, defaultAssigneeId: sql(`select id from "User" where email='owner@lc-paid.ru'`) }));
await t("PUT holidays bad date 2026-13-45", owner.api("PUT", "/api/root/crm/automation", { ...s, holidays: ["2026-13-45"] }));
out.push("  saved holidays: " + sql(`select value::json->>'holidays' from "PlatformSetting" where key='crm:lifecycle'`));
await t("PUT taskStageMax 0", owner.api("PUT", "/api/root/crm/automation", { ...s, taskStageMax: 0 }));
await t("PUT invoiceCycle 'week'", owner.api("PUT", "/api/root/crm/automation", { ...s, invoiceCycle: "week" }));
await t("PUT extra unknown key", owner.api("PUT", "/api/root/crm/automation", { ...s, evil: 1 }));
await t("PUT restore original", owner.api("PUT", "/api/root/crm/automation", original));
out.push("  restored: " + sql(`select value from "PlatformSetting" where key='crm:lifecycle'`));
console.log(out.join("\n"));
await close();
