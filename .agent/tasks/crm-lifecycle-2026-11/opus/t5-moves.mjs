import { login, sql, close } from "./lib.mjs";
const alexey = await login("alexey");
const out = [];
const t = async (label, p) => { const r = await p; out.push(`${label} → ${r.status} ${JSON.stringify(r.data).slice(0, 200)}`); return r; };
const id = (org) => sql(`select id from "CrmDeal" where "organizationId"='${org}'`);
const st = (org) => sql(`select stage||'|manual='||"stageManual"||'|won='||coalesce("wonAt"::text,'-')||'|lost='||coalesce("lostReason",'-')||'|contract='||coalesce("contractSignedAt"::text,'-') from "CrmDeal" where "organizationId"='${org}'`);
await t("pekarnya → registered (back)", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-pekarnya")}`, { stage: "registered" }));
out.push("  " + st("lc-pekarnya"));
await t("month → lost", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-month")}`, { stage: "lost", lostReason: "тест" }));
out.push("  " + st("lc-month") + " open tasks " + sql(`select count(*) from "CrmTask" where "organizationId"='lc-month' and status='open'`));
await t("month lost → won", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-month")}`, { stage: "won" }));
out.push("  " + st("lc-month"));
await t("month won → called", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-month")}`, { stage: "called" }));
out.push("  " + st("lc-month"));
await t("year: contractSigned true", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-year")}`, { contractSigned: true }));
out.push("  " + st("lc-year"));
await t("year: contractSigned false", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-year")}`, { contractSigned: false }));
out.push("  " + st("lc-year"));
await t("expired (registered): contractSigned true", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-expired")}`, { contractSigned: true }));
out.push("  " + st("lc-expired"));
await t("expired: contractSigned false (uncheck)", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-expired")}`, { contractSigned: false }));
out.push("  " + st("lc-expired"));
await t("grace → won manually (not paid)", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-grace")}`, { stage: "won" }));
out.push("  " + st("lc-grace") + " open tasks " + sql(`select count(*) from "CrmTask" where "organizationId"='lc-grace' and status='open'`));
await t("lost with 600-char reason", alexey.api("PATCH", `/api/root/crm/deals/${id("lc-invoice")}`, { stage: "lost", lostReason: "x".repeat(600) }));
console.log(out.join("\n"));
await close();
