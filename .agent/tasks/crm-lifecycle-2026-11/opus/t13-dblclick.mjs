import { login, sql, close, errors, OUT, BASE, sinkLines } from "./lib.mjs";
const note = (s) => console.log(s);
const alexey = await login("alexey");
const p = alexey.page;
const codes = () => sql(`select count(*) from "PromoCode" where "organizationId"='lc-paid'`);
const before = codes(), sinkBefore = sinkLines().length;
await p.goto(`${BASE}/root/crm/tasks`, { waitUntil: "networkidle" });
const task = p.locator("[data-crm-task]").filter({ hasText: "Оплатили» e2e до 13 ноября: повторный контакт" }).first();
await task.locator("[data-crm-offer-open]").click();
await p.waitForSelector("[data-crm-offer-form]");
note(`prefill: discount=${await p.inputValue("[data-offer-discount]")} email=${await p.inputValue("[data-offer-email]")} tier=${await p.inputValue("[data-offer-tier]")}`);
await p.fill("[data-offer-discount]", "7");
await p.fill("[data-offer-email]", "owner@lc-paid.ru");
await p.locator('[role="dialog"] button', { hasText: "Отправить" }).dblclick();
await p.waitForTimeout(8000);
note(`promo codes lc-paid: before ${before}, after ${codes()}; new sink lines: ${sinkLines().length - sinkBefore}`);
note(sinkLines().slice(sinkBefore).join("\n"));
// approval dialog: Maria requests 20% for Stolovaya; Alexey double-clicks Согласовать
const maria = await login("maria");
const stol = sql(`select id from "CrmDeal" where "organizationId"='lc-stolovaya'`);
const req = await maria.api("POST", "/api/root/crm/offers", { dealId: stol, tier: "premium", cycle: "year", points: 3, discountPercent: 20, toEmail: "owner@lc-stolovaya.ru" });
note(`maria request: ${JSON.stringify(req.data)}`);
await p.goto(`${BASE}/root/crm/tasks?kind=approval`, { waitUntil: "networkidle" });
const approval = p.locator('[data-crm-task="approval"]').filter({ hasText: "Согласовать скидку 20 %" }).first();
await approval.locator("[data-approval-approve]").click();
await p.locator('[role="dialog"] button', { hasText: "Согласовать" }).dblclick();
await p.waitForTimeout(4000);
note(`offer tasks created for approval: ${sql(`select count(*) from "CrmTask" where kind='offer' and title like 'Скидка 20 %%'`)}`);
note(`errors: ${errors.length}`);
await close();
